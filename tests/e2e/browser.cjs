const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
let playwright
try { playwright = require('../../.qa/browser/node_modules/playwright') }
catch { playwright = require('../../.qa/playwright/playwright/driver/package') }

async function main() {
  const browser = await playwright.chromium.launch({
    executablePath: process.env.BROWSER_EXECUTABLE || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true,
  })
  const reports = []
  const errors = []
  const context = await browser.newContext({viewport:{width:1440,height:900}})
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  const matrix = []
  try {
    await page.goto(process.env.FRONTEND_URL || 'http://localhost:5173/', {waitUntil:'domcontentloaded'})
    await page.locator('[data-option-id]').first().waitFor()
    assert.ok(await page.locator('.results-scroll').evaluate(el=>el.scrollHeight>el.clientHeight))
    assert.equal(await page.locator('[data-option-id]').count(),4)
    assert.ok(await page.locator('.leaflet-overlay-pane path').count()>0)
    await page.locator('.coordinate-details summary').click()
    const originSearch=page.getByRole('combobox',{name:'Starting place'})
    await originSearch.fill('BORELLA')
    await page.getByRole('option',{name:/Borella transfer point/}).waitFor()
    await originSearch.press('ArrowDown');await originSearch.press('Enter')
    assert.equal(await page.locator('#latitude').inputValue(),'6.916')
    assert.equal(await page.locator('#longitude').inputValue(),'79.878')
    await page.locator('#latitude').fill('6.952')
    assert.equal(await originSearch.inputValue(),'')
    await page.locator('#longitude').fill('79.879')
    await originSearch.fill('no such stop')
    await page.getByText('No matching stops found.').waitFor()
    await originSearch.press('Escape')
    const destinationSearch=page.getByRole('combobox',{name:'Bus drop-off stop'})
    const homagamaResponse=page.waitForResponse(r=>r.url().endsWith('/recommend') && r.request().postDataJSON()?.destination==='homagama')
    await destinationSearch.fill('hOmAgAmA')
    await page.getByRole('option',{name:/Homagama drop-off/}).click()
    assert.equal((await homagamaResponse).status(),200)
    const maharagamaResponse=page.waitForResponse(r=>r.url().endsWith('/recommend') && r.request().postDataJSON()?.destination==='maharagama')
    await destinationSearch.fill('Maharagama')
    await destinationSearch.press('ArrowDown');await destinationSearch.press('Enter')
    assert.equal((await maharagamaResponse).status(),200)
    for (const [query,slug] of [['Nugegoda','nugegoda'],['Kottawa','kottawa'],['Colombo Fort','colombo-fort'],['Battaramulla','battaramulla'],['Kaduwela','kaduwela']]) {
      const responsePromise=page.waitForResponse(r=>r.url().endsWith('/recommend') && r.request().postDataJSON()?.destination===slug)
      await destinationSearch.fill(query)
      await page.getByRole('option',{name:new RegExp(`${query} drop-off`,'i')}).click()
      const response=await responsePromise
      assert.equal(response.status(),200)
      assert.equal((await response.json()).options.length,4)
      await page.locator('[data-option-id]').first().waitFor()
      assert.ok(await page.locator('.leaflet-overlay-pane path').count()>=1)
    }
    const returnResponse=page.waitForResponse(r=>r.url().endsWith('/recommend') && r.request().postDataJSON()?.destination==='maharagama')
    await destinationSearch.fill('Maharagama')
    await destinationSearch.press('ArrowDown');await destinationSearch.press('Enter')
    assert.equal((await returnResponse).status(),200)
    fs.mkdirSync('.qa/screenshots',{recursive:true})
    await page.waitForTimeout(1000)
    await page.screenshot({path:'.qa/screenshots/desktop-controls.png'})
    for (const time of ['08:00','14:00','17:00']) {
      for (const preference of ['cheapest','fastest','comfortable']) {
        const responsePromise=page.waitForResponse(response=>{
          if(!response.url().endsWith('/recommend') || response.request().method()!=='POST')return false
          const body=response.request().postDataJSON()
          return body.preference===preference && body.now===`2026-10-14T${time}:00+05:30` && body.minutes_available===90
        })
        await page.locator('#journey-time').fill(`2026-10-14T${time}`)
        await page.getByRole('button',{name:preference[0].toUpperCase()+preference.slice(1),exact:true}).click()
        const response=await responsePromise
        assert.equal(response.status(),200)
        const data=await response.json()
        const first=page.locator(`[data-option-id="${data.recommended_id}"]`)
        await first.locator('.recommend-label').waitFor()
        assert.equal(await page.locator('[data-option-id]').count(),4)
        assert.equal(await page.locator('.estimate-badge').count(),4)
        matrix.push({time,preference,recommended:data.recommended_id,bucket:data.bucket})
      }
    }
    const backendRecommended=await page.locator('.option:has(.recommend-label)').getAttribute('data-option-id')
    await page.locator('[data-option-id="maharagama-walk-bus"] .option-select').click()
    await page.getByRole('button',{name:/Full taxi 1/}).click()
    await page.getByText('Your mapped journey is hidden by this filter.').waitFor()
    assert.ok(await page.locator('.leaflet-overlay-pane path').count()>=2)
    await page.getByRole('button',{name:'Show it',exact:true}).click()
    await page.locator('#journey-sort').selectOption('cheapest')
    assert.equal(await page.locator('[data-option-id]').first().getAttribute('data-option-id'),'maharagama-walk-bus')
    assert.equal(await page.locator('.option:has(.recommend-label)').getAttribute('data-option-id'),backendRecommended)
    await page.getByRole('button',{name:'Add to compare',exact:true}).nth(0).click()
    await page.getByRole('button',{name:'Add to compare',exact:true}).nth(0).click()
    await page.getByRole('button',{name:'Add to compare',exact:true}).nth(0).click()
    assert.equal(await page.locator('.compare-toggle:disabled').count(),1)
    await page.getByRole('button',{name:'Compare 3',exact:true}).click()
    await page.getByRole('heading',{name:'Compare journeys'}).waitFor()
    assert.equal(await page.locator('.comparison-card').count(),3)
    assert.ok(await page.locator('.best-value').count()>0)
    await page.getByRole('button',{name:'Close comparison'}).click()
    async function budget(minutes,preference,rule) {
      const promise=page.waitForResponse(r=>r.url().endsWith('/recommend') && r.request().postDataJSON()?.minutes_available===minutes && r.request().postDataJSON()?.preference===preference)
      await page.locator('#journey-time').fill('2026-10-14T14:00')
      await page.locator('#minutes').fill(String(minutes))
      await page.getByRole('button',{name:preference[0].toUpperCase()+preference.slice(1),exact:true}).click()
      const data=await (await promise).json()
      assert.equal(data.options[0].rule_code,rule)
      await page.locator(`[data-option-id="${data.recommended_id}"]`).waitFor()
    }
    await budget(90,'cheapest','walk')
    await budget(50,'cheapest','ride')
    await budget(5,'fastest','short_on_time')
    await page.locator('.results-scroll').evaluate(el=>{el.scrollTop=el.scrollHeight})
    assert.ok(await page.locator('.results-scroll').evaluate(el=>el.scrollTop>0))
    await page.screenshot({path:'.qa/screenshots/desktop-results.png'})

    const reportContext=page.waitForResponse(r=>r.url().endsWith('/recommend') && r.request().postDataJSON()?.now==='2026-10-14T08:00:00+05:30' && r.request().postDataJSON()?.minutes_available===90)
    await page.locator('#minutes').fill('90')
    await page.locator('#journey-time').fill('2026-10-14T08:00')
    const reportData=await (await reportContext).json()
    await page.locator(`[data-option-id="${reportData.recommended_id}"] .recommend-label`).waitFor()
    await page.locator(`[data-option-id="${reportData.recommended_id}"] .option-select`).click()
    await page.getByRole('heading',{name:/estimated/i}).first().waitFor()
    await page.screenshot({path:'.qa/screenshots/desktop-details.png'})
    const reportResponse=page.waitForResponse(r=>r.url().endsWith('/crowd-reports') && r.request().method()==='POST')
    await page.getByRole('button',{name:'Seats free',exact:true}).first().click()
    const posted=await reportResponse
    assert.equal(posted.status(),201)
    reports.push((await posted.json()).id)
    await page.getByText('Unverified report saved for the selected journey time.').waitFor()

    await page.route('**/recommend',route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"Database unavailable"}'}))
    await page.getByRole('button',{name:'Refresh journey',exact:true}).click()
    await page.getByText('Database unavailable',{exact:true}).waitFor()
    assert.equal(await page.locator('[data-option-id]').count(),0)
    await page.unroute('**/recommend')
    await page.getByRole('button',{name:'Retry connection',exact:true}).click()
    await page.locator('[data-option-id]').first().waitFor()
    await page.locator('#latitude').fill('0'); await page.locator('#longitude').fill('0')
    await page.getByText('No eligible options in the estimated demo coverage, or already at the drop-off stop.').waitFor()
    assert.equal(await page.locator('[data-option-id]').count(),0)

    const laptop = await context.newPage()
    await laptop.setViewportSize({width:1280,height:800})
    await laptop.goto(process.env.FRONTEND_URL || 'http://localhost:5173/')
    await laptop.locator('[data-option-id]').first().waitFor()
    assert.ok(await laptop.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
    await laptop.screenshot({path:'.qa/screenshots/laptop-web.png',fullPage:true})

    const tablet = await context.newPage()
    await tablet.setViewportSize({width:768,height:1024})
    await tablet.goto(process.env.FRONTEND_URL || 'http://localhost:5173/')
    await tablet.locator('[data-option-id]').first().waitFor()
    assert.ok(await tablet.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
    assert.ok(await tablet.locator('.leaflet-overlay-pane path').count()>=3)
    await tablet.screenshot({path:'.qa/screenshots/tablet-web.png',fullPage:true})

    const narrow = await context.newPage()
    await narrow.setViewportSize({width:390,height:844})
    await narrow.goto(process.env.FRONTEND_URL || 'http://localhost:5173/')
    await narrow.locator('[data-option-id]').first().waitFor()
    assert.ok(await narrow.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
    await narrow.getByRole('button',{name:'Add to compare',exact:true}).nth(0).click()
    await narrow.getByRole('button',{name:'Add to compare',exact:true}).nth(0).click()
    await narrow.getByRole('button',{name:'Compare 2',exact:true}).click()
    await narrow.getByRole('heading',{name:'Compare journeys'}).waitFor()
    assert.equal(await narrow.locator('.comparison-card').count(),2)
    assert.ok(await narrow.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
    await narrow.screenshot({path:'.qa/screenshots/mobile-comparison.png',fullPage:true})
    await narrow.getByRole('button',{name:'Close comparison'}).click()
    await narrow.locator('.map-panel').scrollIntoViewIfNeeded()
    await narrow.locator('.leaflet-tile-loaded').first().waitFor()
    assert.ok(await narrow.locator('.leaflet-overlay-pane path').count()>=3)
    await narrow.locator('.map-panel').screenshot({path:'.qa/screenshots/narrow-map.png'})
    await narrow.screenshot({path:'.qa/screenshots/narrow-web.png',fullPage:true})
    assert.deepEqual(errors,[])
    fs.writeFileSync('.qa/browser-results.json',JSON.stringify({matrix,searchableStops:true,expandedDestinations:true,journeyDiscovery:true,walkRide:true,emptyErrorRetry:true,crowdReport:true,responsiveLayouts:true,consoleErrors:errors},null,2))
    console.log('Browser checks passed: all destinations, filters, sorting, comparison, map-selection preservation, reporting, error/retry, map overlays, and tablet/mobile layouts.')
  } finally {
    await browser.close()
    for(const id of reports) {
      assert.match(id,/^[0-9a-f-]{36}$/)
      execFileSync('docker',['compose','exec','-T','db','psql','-U','boardhere','-d','boardhere','-v','ON_ERROR_STOP=1','-c',`delete from boardhere.crowd_reports where id='${id}'`],{cwd:path.resolve(__dirname,'../..'),stdio:'pipe'})
    }
  }
}
main().catch(error=>{console.error(error);process.exitCode=1})
